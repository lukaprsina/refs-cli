//! `refs.lock`: what each active Repo resolved to. Serialisation only; no decisions.

use std::path::Path;

use serde::{Deserialize, Serialize};

use sha2::{Digest, Sha256};

use crate::active::ActiveSet;
use crate::diagnostic::LockError;
use crate::source::Pin;

const HEADER: &str = "# Generated by refs. Do not edit.\n";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Lock {
    pub version: u32,
    /// The `refs` version that last wrote the block.
    pub generator: String,
    pub config_hash: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub repo: Vec<Entry>,
}

/// One locked Repo. The `source` tag and its fields live in the `Pin`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Entry {
    pub id: String,
    #[serde(flatten)]
    pub pin: Pin,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub paths: Vec<String>,
}

impl Lock {
    pub fn parse(text: &str) -> Result<Lock, LockError> {
        toml::from_str(text).map_err(|e| LockError::Invalid {
            message: e.message().to_string(),
        })
    }

    /// Stable text: entries sorted by id.
    pub fn to_toml(&self) -> String {
        let mut sorted = self.clone();
        sorted.repo.sort_by(|a, b| a.id.cmp(&b.id));
        let body = toml::to_string(&sorted).expect("a lock is always serialisable");
        format!("{HEADER}{body}")
    }

    /// Write via a temp file in the same directory, then rename, so a reader never
    /// sees a partial lock.
    pub fn write(&self, path: &Path) -> Result<(), LockError> {
        let mut tmp = path.as_os_str().to_owned();
        tmp.push(".tmp");
        let tmp = Path::new(&tmp);
        std::fs::write(tmp, self.to_toml())
            .and_then(|()| std::fs::rename(tmp, path))
            .map_err(|source| {
                let _ = std::fs::remove_file(tmp);
                LockError::Write {
                    path: path.display().to_string(),
                    source,
                }
            })
    }
}

/// Hash of the fields that decide what is resolved and checked out: each active repo's
/// id, source, url, ref (`HEAD` when absent) and paths, sorted by id. Display fields and
/// grouping are left out, so editing them does not stale the lock (spec §10.2).
pub fn config_hash(active: &ActiveSet) -> String {
    let mut repos: Vec<_> = active.sections.iter().flat_map(|s| &s.repos).collect();
    repos.sort_by_key(|(id, _)| *id);

    let mut hasher = Sha256::new();
    // Every field is NUL-terminated and the paths are counted, so no two different
    // inputs share an encoding.
    let mut field = |value: &str| {
        hasher.update(value.as_bytes());
        hasher.update([0]);
    };
    for (id, repo) in repos {
        field(id);
        field("git");
        field(repo.url.as_ref());
        field(repo.git_ref.as_ref().map_or("HEAD", |r| r.as_ref().as_str()));
        field(&repo.paths.len().to_string());
        for path in &repo.paths {
            field(path.as_ref());
        }
    }
    let hex: String = hasher.finalize().iter().map(|b| format!("{b:02x}")).collect();
    format!("sha256:{hex}")
}
