mod package_lock {
    use super::*;

    const V3: &str = r#"{
  "name": "web",
  "lockfileVersion": 3,
  "packages": {
    "": {
      "name": "web",
      "dependencies": { "react": "^18.2.0", "lodash-alias": "npm:lodash@^4" },
      "devDependencies": { "@babel/core": "^7.23.0" }
    },
    "node_modules/@babel/core": { "version": "7.23.2", "resolved": "https://registry.npmjs.org/@babel/core/-/core-7.23.2.tgz" },
    "node_modules/react": { "version": "18.2.0", "resolved": "https://registry.npmjs.org/react/-/react-18.2.0.tgz" },
    "node_modules/lodash-alias": { "name": "lodash", "version": "4.17.21", "resolved": "https://registry.npmjs.org/lodash/-/lodash-4.17.21.tgz" },
    "node_modules/ms": { "version": "2.1.3", "resolved": "https://registry.npmjs.org/ms/-/ms-2.1.3.tgz" },
    "node_modules/debug/node_modules/ms": { "version": "2.0.0", "resolved": "https://registry.npmjs.org/ms/-/ms-2.0.0.tgz" },
    "node_modules/local": { "resolved": "packages/local", "link": true },
    "node_modules/fromgit": { "version": "1.0.0", "resolved": "git+ssh://git@github.com/me/fromgit.git#abc" },
    "packages/local": { "version": "0.0.1" }
  }
}"#;

    const V1: &str = r#"{
  "lockfileVersion": 1,
  "dependencies": {
    "ms": {
      "version": "2.1.3",
      "resolved": "https://registry.npmjs.org/ms/-/ms-2.1.3.tgz"
    },
    "debug": {
      "version": "4.3.4",
      "resolved": "https://registry.npmjs.org/debug/-/debug-4.3.4.tgz",
      "requires": { "ms": "2.1.2" },
      "dependencies": {
        "ms": { "version": "2.1.2", "resolved": "https://registry.npmjs.org/ms/-/ms-2.1.2.tgz" }
      }
    }
  }
}"#;

    fn of3(name: &str) -> Vec<Used> {
        used_versions("package-lock.json", name, V3).unwrap()
    }

    #[test]
    fn a_hoisted_package_nobody_in_the_project_names_is_not_direct() {
        assert_eq!(of3("ms"), [used("2.0.0", false), used("2.1.3", false)]);
    }

    #[test]
    fn an_alias_is_found_by_the_real_name() {
        assert_eq!(of3("lodash"), [used("4.17.21", true)]);
        assert_eq!(of3("lodash-alias"), []);
        assert_eq!(of3("@babel/core"), [used("7.23.2", true)]);
    }

    #[test]
    fn a_link_a_git_package_and_a_workspace_are_not_registry_versions() {
        assert_eq!(of3("local"), []);
        assert_eq!(of3("fromgit"), []);
    }

    #[test]
    fn version_1_lists_every_version_and_marks_none_direct() {
        assert_eq!(
            used_versions("package-lock.json", "ms", V1).unwrap(),
            [used("2.1.2", false), used("2.1.3", false)]
        );
        assert_eq!(
            used_versions("package-lock.json", "debug", V1).unwrap(),
            [used("4.3.4", false)]
        );
    }

    #[test]
    fn version_1_git_and_file_entries_are_not_registry_versions() {
        let text = r#"{
  "lockfileVersion": 1,
  "dependencies": {
    "fromgit": { "version": "github:me/fromgit#abc" },
    "fromfile": { "version": "file:../fromfile" },
    "fromurl": { "version": "git+ssh://git@github.com/me/fromurl.git#abc" }
  }
}"#;
        for name in ["fromgit", "fromfile", "fromurl"] {
            assert_eq!(used_versions("package-lock.json", name, text).unwrap(), []);
        }
    }

    #[test]
    fn a_package_not_in_the_lockfile_has_no_version() {
        assert_eq!(of3("left-pad"), []);
        assert_eq!(
            used_versions("package-lock.json", "left-pad", V1).unwrap(),
            []
        );
    }

    #[test]
    fn of_several_versions_only_the_one_the_project_names_is_direct() {
        let text = r#"{
  "lockfileVersion": 3,
  "packages": {
    "": { "dependencies": { "ms": "^2.1.0" } },
    "node_modules/ms": { "version": "2.1.3", "resolved": "https://registry.npmjs.org/ms/-/ms-2.1.3.tgz" },
    "node_modules/debug/node_modules/ms": { "version": "2.0.0", "resolved": "https://registry.npmjs.org/ms/-/ms-2.0.0.tgz" }
  }
}"#;
        assert_eq!(
            used_versions("package-lock.json", "ms", text).unwrap(),
            [used("2.0.0", false), used("2.1.3", true)]
        );
    }

    #[test]
    fn a_lockfile_that_is_not_json_is_an_error() {
        assert!(used_versions("package-lock.json", "react", "nope").is_err());
    }
}

const NONE: [&str; 0] = [];

fn versions(file: &str, text: &str, name: &str) -> Vec<String> {
    used_versions(file, name, text)
        .unwrap()
        .into_iter()
        .map(|used| used.version)
        .collect()
}

mod pnpm {
    use super::*;

    const PNPM_V9: &str = include_str!("fixtures/used/pnpm-v9-workspace.yaml");

    fn pnpm(text: &str, name: &str) -> Vec<String> {
        versions("pnpm-lock.yaml", text, name)
    }

    #[test]
    fn pnpm_v5_top_level_string_form() {
        let text = r#"lockfileVersion: '5.4'

specifiers:
  zod: ^3.22.0

dependencies:
  zod: 3.22.0

packages:
  /zod/3.22.0:
    resolution: {}
"#;
        assert_eq!(pnpm(text, "zod"), ["3.22.0"]);
    }

    #[test]
    fn pnpm_v6_top_level_object_form() {
        let text = r#"lockfileVersion: '6.0'

dependencies:
  zod:
    specifier: ^3.22.0
    version: 3.22.0

packages:
  /zod@3.22.0:
    resolution: {}
"#;
        assert_eq!(pnpm(text, "zod"), ["3.22.0"]);
    }

    #[test]
    fn pnpm_v9_alias_is_not_found_under_its_alias() {
        let text = r#"lockfileVersion: '9.0'

importers:
  .:
    dependencies:
      foo:
        specifier: npm:bar@^1.0.0
        version: bar@1.0.0

packages:
  bar@1.0.0:
    resolution: {}
"#;
        assert!(pnpm(text, "foo").is_empty());
    }

    #[test]
    fn pnpm_scoped_fallback_to_packages_key() {
        let text = r#"lockfileVersion: '9.0'

packages:
  '@scope/pkg@1.2.3':
    resolution: {}
"#;
        assert_eq!(pnpm(text, "@scope/pkg"), ["1.2.3"]);
    }

    #[test]
    fn pnpm_returns_none_when_absent() {
        let text = r#"lockfileVersion: '9.0'

importers:
  .:
    dependencies:
      react:
        specifier: ^18.0.0
        version: 18.0.0
"#;
        assert_eq!(pnpm(text, "zod"), NONE);
    }

    #[test]
    fn pnpm_optional_dependencies_in_importer() {
        let text = r#"lockfileVersion: '9.0'

importers:
  .:
    optionalDependencies:
      fsevents:
        specifier: ^2.3.0
        version: 2.3.3
"#;
        assert_eq!(pnpm(text, "fsevents"), ["2.3.3"]);
    }

    #[test]
    fn pnpm_workspace_link_in_first_importer_does_not_block_later_real_version() {
        // First importer has a `link:` version; second has a real one. The workspace link
        // is skipped and the real version is found.
        let text = r#"lockfileVersion: '9.0'

importers:
  apps/web:
    dependencies:
      shared:
        specifier: workspace:^
        version: link:../../packages/shared
  apps/docs:
    dependencies:
      shared:
        specifier: ^1.2.3
        version: 1.2.3
"#;
        assert_eq!(pnpm(text, "shared"), ["1.2.3"]);
    }

    #[test]
    fn pnpm_skips_file_protocol_in_importer() {
        let text = r#"lockfileVersion: '9.0'

importers:
  .:
    dependencies:
      tarball-pkg:
        specifier: file:./pkg.tgz
        version: file:pkg.tgz
"#;
        assert_eq!(pnpm(text, "tarball-pkg"), NONE);
    }

    #[test]
    fn pnpm_fixture_direct_importer_dep() {
        assert_eq!(pnpm(PNPM_V9, "next"), ["14.0.0"]);
    }

    #[test]
    fn pnpm_fixture_scoped_direct_dep() {
        assert_eq!(pnpm(PNPM_V9, "@types/react"), ["18.2.45"]);
    }

    #[test]
    fn pnpm_fixture_transitive_via_bfs() {
        // js-tokens is only reachable via loose-envify; not a direct dep.
        assert_eq!(pnpm(PNPM_V9, "js-tokens"), ["4.0.0"]);
    }

    #[test]
    fn pnpm_text_that_is_not_yaml_is_an_error() {
        assert!(used_versions("pnpm-lock.yaml", "zod", "importers: [unclosed").is_err());
    }

    #[test]
    fn pnpm_marks_what_an_importer_lists_as_direct() {
        let used = |name| used_versions("pnpm-lock.yaml", name, PNPM_V9).unwrap();
        assert_eq!(
            used("react"),
            [super::used("17.0.2", true), super::used("18.2.0", true)]
        );
        assert_eq!(
            used("scheduler"),
            [super::used("0.20.2", false), super::used("0.23.0", false)]
        );
    }

    #[test]
    fn pnpm_fixture_absent() {
        assert_eq!(pnpm(PNPM_V9, "definitely-not-here"), NONE);
    }
}

mod yarn {
    use super::*;

    const YARN_V1: &str = include_str!("fixtures/used/yarn-v1.lock");
    const YARN_BERRY: &str = include_str!("fixtures/used/yarn-berry.lock");

    fn yarn(text: &str, name: &str) -> Vec<String> {
        versions("yarn.lock", text, name)
    }

    #[test]
    fn yarn_v1_multi_specifier_match_not_first() {
        let text = "# yarn lockfile v1\n\
\n\
\n\
\"foo@^1.0.0\":\n  \
version \"1.0.0\"\n\
\n\
\"bar@^1.0.0\", \"bar@~1.2.0\":\n  \
version \"1.2.3\"\n";
        assert_eq!(yarn(text, "bar"), ["1.2.3"]);
    }

    #[test]
    fn yarn_crlf_line_endings() {
        let text = "# yarn lockfile v1\r\n\r\n\r\n\"zod@^3.22.0\":\r\n  version \"3.22.0\"\r\n";
        assert_eq!(yarn(text, "zod"), ["3.22.0"]);
    }

    #[test]
    fn yarn_berry_inline_comment_stripped() {
        let text = "__metadata:\n  \
version: 6\n\
\n\
\"zod@npm:^3.22.0\":\n  \
version: 3.22.0 # pinned\n";
        assert_eq!(yarn(text, "zod"), ["3.22.0"]);
    }

    #[test]
    fn yarn_berry_workspace_block_does_not_block_later_real_block() {
        // A workspace self-reference should be skipped, but a real block for
        // the same name later in the file should still be found.
        let text = "__metadata:\n  \
version: 6\n\
\n\
\"foo@workspace:packages/foo\":\n  \
version: 0.0.0-use.local\n  \
resolution: \"foo@workspace:packages/foo\"\n\
\n\
\"foo@npm:^1.0.0\":\n  \
version: 1.2.3\n  \
resolution: \"foo@npm:1.2.3\"\n";
        assert_eq!(yarn(text, "foo"), ["1.2.3"]);
    }

    #[test]
    fn yarn_v1_fixture_scoped() {
        assert_eq!(yarn(YARN_V1, "@babel/core"), ["7.23.0"]);
        assert_eq!(yarn(YARN_V1, "@types/react"), ["18.2.45"]);
    }

    #[test]
    fn yarn_v1_fixture_multi_specifier() {
        // lodash@^4.17.21 is in a multi-specifier header, and lodash@^3 has a block of its own.
        assert_eq!(yarn(YARN_V1, "lodash"), ["3.10.1", "4.17.21"]);
    }

    #[test]
    fn yarn_berry_alias_is_found_by_the_real_name_not_the_alias() {
        let text = "__metadata:\n  version: 6\n\n\"short@npm:@scope/long@^2.0.0\":\n  version: 2.1.0\n  resolution: \"short@npm:@scope/long@2.1.0\"\n\n\"plain@npm:^1.0.0\":\n  version: 1.4.0\n";
        assert_eq!(yarn(text, "@scope/long"), ["2.1.0"]);
        assert_eq!(yarn(text, "short"), NONE);
        assert_eq!(yarn(text, "plain"), ["1.4.0"]);
    }

    #[test]
    fn yarn_cannot_say_what_is_direct() {
        let found = used_versions("yarn.lock", "react", YARN_V1).unwrap();
        assert!(!found.is_empty() && found.iter().all(|used| !used.direct));
    }

    #[test]
    fn yarn_v1_fixture_absent() {
        assert_eq!(yarn(YARN_V1, "not-installed-anywhere"), NONE);
    }

    #[test]
    fn yarn_berry_fixture_comma_specifier() {
        assert_eq!(yarn(YARN_BERRY, "lodash"), ["4.17.21"]);
    }
}

